const IDS = ["a", "b", "c", "d"];

/** Spread the key across a..d by the item id, so position carries no signal. */
function slot(id) {
  let h = 13;
  for (const ch of id) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  return h % 4;
}

/** mcq(id, domain, difficulty, topic, skill, prompt, [right, wrong, wrong, wrong], explanation) */
const mcq = (id, domain, difficulty, topic, skill, prompt, [right, ...wrongs], explanation) => {
  const pos = slot(id);
  const texts = [...wrongs];
  texts.splice(pos, 0, right);
  return {
    type: "mcq",
    id,
    domain,
    difficulty,
    topic,
    skill,
    prompt,
    options: texts.map((text, i) => ({ id: IDS[i], text })),
    correct: IDS[pos],
    explanation,
  };
};

