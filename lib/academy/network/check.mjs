/**
 * CONTENT CHECK — COMPUTER NETWORKING (NW-101)
 *
 * One function, used by scripts/nwCheck.mjs (the fast loop while writing)
 * and lib/academy/validateContent.mjs (the build). It proves, module by
 * module:
 *
 *   - structure: one graded practice per atom, assessments well formed,
 *     every curriculum topic taught, in order, with the practical last;
 *   - TEACH BEFORE USE: every command a lab's model answer types, every
 *     command a terminal exercise accepts and every capture filter it needs
 *     appears in the teaching text (explain, tables, tasks) of that atom or
 *     an earlier one, so no practice asks for something the course has not
 *     shown. Hints do not count as teaching;
 *   - NetLabs fail as shipped, pass after their model answer, and reject no
 *     model command; starting configs apply cleanly;
 *   - netCalc answers equal what the named calculator computes;
 *   - terminal and capture exercises are answerable from their recordings;
 *   - Python (Module 10 only) prints what the lesson claims, and challenge
 *     solutions pass while their starters fail.
 */
import { execFileSync } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const ROOT = new URL("../../../", import.meta.url);
const norm = (t) => String(t ?? "").split(/\r?\n/).map((l) => l.trimEnd()).join("\n").trim();
const flat = (t) => String(t ?? "").toLowerCase().replace(/\s+/g, " ");

export const NW_GRADED = ["codeChallenge", "codeExercise", "decision", "netLab", "netCalc", "captureExercise",
  "terminalExercise", "firewallExercise", "permsExercise", "huntExercise"];

/** The words of a command that must have been taught: up to the first argument. */
export function commandPhrase(line) {
  const out = [];
  for (const tok of String(line).trim().split(/\s+/)) {
    if (out.length >= 4) break;
    if (/[0-9.:@'"=|>]/.test(tok) || (/[A-Z]/.test(tok) && out.length > 0)) break;
    out.push(tok.toLowerCase());
  }
  return out.join(" ");
}

function teachingText(atom) {
  const parts = [atom.title, atom.explain, atom.analogy, atom.example];
  if (atom.table) parts.push(...atom.table.rows.flat(), ...(atom.table.headers || []));
  for (const k of ["netLab", "netDemo"]) if (atom[k]) parts.push(atom[k].task, atom[k].intro);
  for (const k of ["terminal", "terminalExercise"]) if (atom[k]) parts.push(atom[k].goal, atom[k].intro);
  for (const k of ["capture", "captureExercise"]) if (atom[k]) parts.push(atom[k].task, atom[k].note);
  return flat(parts.filter(Boolean).join(" \n "));
}

export async function checkNetworking({ filter = "", sync = false } = {}) {
  const { NETWORKING_COURSE, NETWORKING_MODULE_IDS } = await import(new URL("src/academy/data/networkingCourse.js", ROOT));
  const sim = await import(new URL("lib/academy/network/netsim.js", ROOT));
  const { NETLAB_SOLUTIONS } = await import(new URL("lib/academy/network/solutions.mjs", ROOT));
  const calc = await import(new URL("lib/academy/network/calc.js", ROOT));
  const shell = await import(new URL("lib/academy/cyber/shell.js", ROOT));
  const { applyFilter } = await import(new URL("lib/academy/cyber/packets.js", ROOT));
  const prac = await import(new URL("lib/academy/network/practice.mjs", ROOT));

  const errors = [];
  const allWritten = NETWORKING_MODULE_IDS.filter((id) => existsSync(new URL(`src/academy/data/lessons/${id}.js`, ROOT)));
  const modules = allWritten.filter((id) => id.startsWith(filter));

  if (sync) {
    const name = (id) => id.replace(/^nw-/, "NW_").replace(/-.*$/, "").toUpperCase();
    const lessonReg = `/**\n * COMPUTER NETWORKING — LESSON REGISTRY\n *\n * GENERATED by scripts/nwCheck.mjs --sync. One import per written module;\n * a module missing here shows as "coming soon" in the curriculum tree.\n */\n\n${allWritten.map((id) => `import { LESSONS as ${name(id)} } from "./${id}.js";`).join("\n")}\n\nexport const NETWORKING_LESSONS = {\n${allWritten.map((id) => `  "${id}": ${name(id)},`).join("\n")}\n};\n`;
    writeFileSync(new URL("src/academy/data/lessons/nw-registry.js", ROOT), lessonReg);
    const withBank = allWritten.filter((id) => existsSync(new URL(`lib/academy/assessments/${id}.js`, ROOT)));
    const bankReg = `/**\n * ASSESSMENTS · COMPUTER NETWORKING — REGISTRY\n *\n * SERVER ONLY. Never import this from anything under src/.\n * GENERATED by scripts/nwCheck.mjs --sync.\n */\n\n${withBank.map((id) => `import { ASSESSMENTS as ${name(id)} } from "./${id}.js";`).join("\n")}\n\nexport const NETWORKING_ASSESSMENTS = {\n${withBank.map((id) => `  ...${name(id)},`).join("\n")}\n};\n`;
    writeFileSync(new URL("lib/academy/assessments/nw-registry.js", ROOT), bankReg);
  }

  // Every written module is loaded for teach-before-use, even when filtering.
  const course = [];
  let assessments = {};
  const written = {};
  for (const id of allWritten) {
    const mod = await import(new URL(`src/academy/data/lessons/${id}.js`, ROOT));
    course.push(...mod.LESSONS);
    written[id] = mod.LESSONS.reduce((n, l) => n + l.atoms.length, 0);
    if (!modules.includes(id)) continue;
    const aPath = new URL(`lib/academy/assessments/${id}.js`, ROOT);
    if (!existsSync(aPath)) { errors.push(`${id}: no assessment file`); continue; }
    assessments = { ...assessments, ...(await import(aPath)).ASSESSMENTS };
  }
  const lessons = course.filter((l) => modules.includes(l.moduleId));

  /* ── structure ─────────────────────────────────────────────────────── */
  const atomIds = new Set();
  for (const l of course) for (const a of l.atoms) {
    if (atomIds.has(a.id)) errors.push(`duplicate atom ${a.id}`);
    atomIds.add(a.id);
  }
  for (const l of lessons) {
    if (!l.atoms.some((a) => NW_GRADED.some((k) => a[k]))) errors.push(`${l.id}: no graded practice`);
    for (const a of l.atoms) {
      if (!a.explain) errors.push(`${a.id}: no explain`);
      const g = NW_GRADED.filter((k) => a[k]);
      if (g.length > 1) errors.push(`${a.id}: more than one graded practice (${g.join(", ")})`);
      if (!g.length) errors.push(`${a.id}: no graded practice`);
      if (a.decision) {
        const d = a.decision;
        if (!d.options.some((o) => o.id === d.correct)) errors.push(`${a.id}: decision key not an option`);
        for (const o of d.options) if (o.id !== d.correct && !o.whyWrong) errors.push(`${a.id}: option ${o.id} has no whyWrong`);
        if (!d.options.find((o) => o.id === d.correct)?.why) errors.push(`${a.id}: correct option has no why`);
      }
      if ((a.codeExercise || a.codeChallenge || a.code) && !l.moduleId.startsWith("nw-m10")) {
        errors.push(`${a.id}: Python practice before Module 10, where Python is taught`);
      }
    }
    const as = assessments[l.id];
    if (!as) { errors.push(`${l.id}: no assessment`); continue; }
    if (as.questions.length < 4 || as.questions.length > 5) errors.push(`${l.id}: ${as.questions.length} questions`);
    for (const q of as.questions) {
      if (!q.options.some((o) => o.id === q.correct)) errors.push(`${q.id}: key not an option`);
      if (!q.explanation) errors.push(`${q.id}: no explanation`);
      for (const o of q.options) if (o.id !== q.correct && !q.whyWrong?.[o.id]) errors.push(`${q.id}: no whyWrong for ${o.id}`);
      if (!l.atoms.some((a) => a.id === q.atomId)) errors.push(`${q.id}: atom ${q.atomId} is not in ${l.id}`);
    }
  }
  for (const id of Object.keys(assessments)) if (!lessons.some((l) => l.id === id)) errors.push(`assessment ${id} has no lesson`);
  const qids = Object.values(assessments).flatMap((a) => a.questions.map((q) => q.id));
  if (new Set(qids).size !== qids.length) errors.push("duplicate assessment question ids");

  /* ── curriculum coverage and order ─────────────────────────────────── */
  const outline = NETWORKING_COURSE.months.flatMap((m) => m.modules);
  for (const id of modules) {
    const mod = outline.find((m) => m.id === id);
    const here = lessons.filter((l) => l.moduleId === id);
    if (!here.length) errors.push(`${id}: no lessons with this moduleId`);
    const covered = new Set(here.flatMap((l) => l.covers || []));
    const required = mod.curriculum.map(([n]) => n);
    const missing = required.filter((n) => !covered.has(n));
    const extra = [...covered].filter((n) => !required.includes(n));
    if (missing.length) errors.push(`${id}: topics not taught: ${missing.join(", ")}`);
    if (extra.length) errors.push(`${id}: lessons claim topics from elsewhere: ${extra.join(", ")}`);
    const last = here[here.length - 1];
    if (!last?.task?.prompts?.length) errors.push(`${id}: last lesson has no practical task`);
    if (last && !last.covers.includes(`${mod.order}.P`)) errors.push(`${id}: the last lesson does not cover ${mod.order}.P`);
    here.forEach((l, i) => { if (l.order !== i + 1) errors.push(`${l.id}: order ${l.order}, expected ${i + 1}`); });
    const seq = here.flatMap((l) => l.covers);
    const idx = (n) => required.indexOf(n);
    for (let i = 1; i < seq.length; i += 1) if (idx(seq[i]) < idx(seq[i - 1])) errors.push(`${id}: topic ${seq[i]} is taught after ${seq[i - 1]}`);
    if (!sync && mod.atoms !== written[id]) errors.push(`${id}: outline says ${mod.atoms} atoms, ${written[id]} written (run with --sync)`);
  }
  const lessonIds = new Set();
  for (const l of course) {
    if (lessonIds.has(l.id)) errors.push(`duplicate lesson ${l.id}`);
    lessonIds.add(l.id);
  }

  /* ── teach before use ──────────────────────────────────────────────── */
  const ordered = allWritten.flatMap((id) => course.filter((l) => l.moduleId === id));
  let corpus = "";
  for (const l of ordered) for (const a of l.atoms) {
    corpus += " \n " + teachingText(a);
    if (!modules.includes(l.moduleId)) continue;
    const needs = [];
    if (a.netLab) for (const [, line] of NETLAB_SOLUTIONS[a.id] || []) needs.push(commandPhrase(line));
    if (a.terminalExercise) for (const c of a.terminalExercise.accept || []) needs.push(commandPhrase(c));
    if (a.captureExercise && prac.NW_CAPTURE_SOLUTIONS[a.id]) needs.push(flat(prac.NW_CAPTURE_SOLUTIONS[a.id].filter));
    for (const phrase of [...new Set(needs)].filter(Boolean)) {
      if (!corpus.includes(flat(phrase))) errors.push(`${a.id}: uses "${phrase}" before any lesson text teaches it`);
    }
  }

  /* ── NetLabs ───────────────────────────────────────────────────────── */
  let labs = 0;
  for (const l of lessons) for (const a of l.atoms) {
    for (const spec of [a.netLab, a.netDemo].filter(Boolean)) {
      for (const [dev, text] of Object.entries(spec.config || {})) {
        const scratch = sim.createWorld({ devices: spec.devices, links: spec.links });
        const errs = sim.applyConfig(scratch, dev, text).filter((e) => !(spec.expectConfigErrors || []).some((x) => e.includes(x)));
        if (errs.length) errors.push(`${a.id}: starting config of ${dev} rejected: ${errs[0]}`);
      }
    }
    if (!a.netLab) continue;
    labs += 1;
    const spec = a.netLab;
    const before = sim.checkGoals(sim.createWorld(spec), spec.goals);
    if (before.every((g) => g.ok)) errors.push(`${a.id}: NetLab is already solved before the learner types anything`);
    const sol = NETLAB_SOLUTIONS[a.id];
    if (!sol) { errors.push(`${a.id}: no model answer in lib/academy/network/solutions.mjs`); continue; }
    const w = sim.createWorld(spec);
    for (const t of sim.runScript(w, sol)) {
      if (/% Invalid input|% Incomplete|% Ambiguous|Invalid Command\.|Unknown setting|Choose a usable/.test(t.output)) errors.push(`${a.id}: model answer step rejected on ${t.id}: "${t.line}" → ${t.output.split("\n").pop()}`);
    }
    for (const g of sim.checkGoals(w, spec.goals).filter((x) => !x.ok)) errors.push(`${a.id}: model answer does not meet goal "${g.label}" ${g.detail || ""}`);
  }

  /* ── netCalc ───────────────────────────────────────────────────────── */
  let calcs = 0;
  for (const l of lessons) for (const a of l.atoms) {
    const c = a.netCalc;
    if (!c) continue;
    calcs += 1;
    if (!c.questions?.length) errors.push(`${a.id}: netCalc has no questions`);
    for (const [i, q] of (c.questions || []).entries()) {
      const at = `${a.id} q${i + 1}`;
      if (!q.q || q.answer === undefined || !q.hint || !q.working) errors.push(`${at}: needs q, answer, hint and working`);
      if (!calc.answerMatches(q, q.answer)) errors.push(`${at}: its own answer does not match`);
      if (q.check) {
        const fn = calc.CALCULATORS[q.check.fn];
        if (!fn) errors.push(`${at}: unknown calculator ${q.check.fn}`);
        else {
          const got = fn(q.check.arg);
          if (!calc.answerMatches(q, got)) errors.push(`${at}: answer ${q.answer}, but ${q.check.fn}(${q.check.arg}) gives ${got}`);
        }
      }
    }
  }

  /* ── recorded terminals and captures ───────────────────────────────── */
  let terms = 0;
  let caps = 0;
  for (const l of lessons) for (const a of l.atoms) {
    for (const t of [a.terminal, a.terminalExercise].filter(Boolean)) {
      terms += 1;
      if (!Object.keys(t.commands || {}).length) errors.push(`${a.id}: terminal has no recorded commands`);
      for (const c of t.available || []) if (shell.run(t, c).status !== "ok") errors.push(`${a.id}: listed command "${c}" was not recorded`);
    }
    if (a.terminalExercise) {
      const t = a.terminalExercise;
      if (!t.accept?.length) errors.push(`${a.id}: terminal exercise accepts nothing`);
      for (const c of t.accept || []) if (shell.run(t, c).status !== "ok") errors.push(`${a.id}: accepted command "${c}" was not recorded`);
      if (prac.NW_TERMINAL_EXPECTED[a.id] === undefined) errors.push(`${a.id}: no expected command in lib/academy/network/practice.mjs`);
    }
    for (const c of [a.capture, a.captureExercise].filter(Boolean)) {
      caps += 1;
      if (!c.packets?.length) errors.push(`${a.id}: capture has no packets`);
    }
    if (a.captureExercise) {
      const sol = prac.NW_CAPTURE_SOLUTIONS[a.id];
      if (!sol) errors.push(`${a.id}: no capture solution in lib/academy/network/practice.mjs`);
      else if (!applyFilter(a.captureExercise.packets, sol.filter).ok) errors.push(`${a.id}: model filter does not parse`);
    }
  }

  /* ── Python (Module 10) ────────────────────────────────────────────── */
  const python = ["python", "python3"].find((c) => { try { execFileSync(c, ["--version"], { stdio: "pipe" }); return true; } catch { return false; } });
  let snippets = 0;
  let challenges = 0;
  const pyAtoms = lessons.flatMap((l) => l.atoms);
  if (python && pyAtoms.some((a) => a.code || a.codeExercise || a.codeChallenge)) {
    const { PY_HARNESS, PY_HARNESS_BATCH_MAIN } = await import(new URL("src/academy/pyHarness.js", ROOT));
    const dir = mkdtempSync(join(tmpdir(), "nw-check-"));
    for (const a of pyAtoms) for (const spec of [a.code, a.codeExercise]) {
      if (!spec?.code || spec.language !== "python") continue;
      snippets += 1;
      const file = join(dir, `${a.id}.py`);
      writeFileSync(file, spec.code, "utf8");
      let out = "", err = "";
      try { out = execFileSync(python, [file], { stdio: "pipe", encoding: "utf8", cwd: dir, env: { ...process.env, PYTHONIOENCODING: "utf-8" } }); }
      catch (e) { out = e.stdout || ""; err = norm(e.stderr).split("\n").pop(); }
      if (err) { errors.push(`${a.id}: raised ${err}`); continue; }
      if (spec.expectedOutput !== undefined && norm(out) !== norm(spec.expectedOutput)) errors.push(`${a.id}: output differs.\n   lesson: ${JSON.stringify(norm(spec.expectedOutput))}\n   python: ${JSON.stringify(norm(out))}`);
    }
    const chs = pyAtoms.filter((a) => a.codeChallenge).map((a) => ({ id: a.id, ...a.codeChallenge }));
    if (chs.length) {
      const harness = join(dir, "harness.py");
      const jobsFile = join(dir, "jobs.json");
      writeFileSync(harness, PY_HARNESS + PY_HARNESS_BATCH_MAIN, "utf8");
      writeFileSync(jobsFile, JSON.stringify([
        ...chs.map((c) => ({ id: `${c.id}#solution`, code: c.solution, tests: c.tests })),
        ...chs.map((c) => ({ id: `${c.id}#starter`, code: c.starter || "", tests: c.tests })),
      ]), "utf8");
      const results = JSON.parse(execFileSync(python, [harness, jobsFile], { stdio: "pipe", encoding: "utf8", cwd: dir, maxBuffer: 64 << 20 }));
      const by = new Map(results.map((r) => [r.id, r.result]));
      for (const c of chs) {
        challenges += 1;
        const sol = by.get(`${c.id}#solution`);
        const st = by.get(`${c.id}#starter`);
        if (!sol?.passed) { const last = sol?.results?.slice(-1)[0] || {}; errors.push(`${c.id}: model solution fails: ${last.error || last.message}`); }
        if (st?.passed) errors.push(`${c.id}: starter already passes`);
        const bare = c.tests.flatMap((t) => t.check.split("\n")).filter((line) => /^\s*assert\b/.test(line) && !/,\s*(f?["']|\()/.test(line));
        if (bare.length) errors.push(`${c.id}: assert without a message: ${bare[0].trim()}`);
      }
    }
  }

  /* ── final exam: subnetting keys recomputed ────────────────────────── */
  const { ITEMS: EXAM_ITEMS } = await import(new URL("lib/academy/finalExam/networking/bank.js", ROOT));
  for (const item of EXAM_ITEMS.filter((i) => i.calc)) {
    const fn = calc.CALCULATORS[item.calc.fn];
    const keyed = item.options.find((o) => o.id === item.correct)?.text;
    if (!fn) errors.push(`${item.id}: unknown calculator ${item.calc.fn}`);
    else if (calc.normaliseAnswer(fn(item.calc.arg)) !== calc.normaliseAnswer(keyed)) errors.push(`${item.id}: keyed "${keyed}", but ${item.calc.fn}(${item.calc.arg}) gives ${fn(item.calc.arg)}`);
    else if (item.options.some((o) => o.id !== item.correct && calc.normaliseAnswer(o.text) === calc.normaliseAnswer(keyed))) errors.push(`${item.id}: a distractor equals the key`);
  }

  /* ── outline atom counts ───────────────────────────────────────────── */
  if (sync) {
    const p = new URL("src/academy/data/networkingCourse.js", ROOT);
    let src = readFileSync(p, "utf8");
    for (const id of allWritten) src = src.replace(new RegExp(`(id: "${id}",[\\s\\S]*?atoms: )\\d+`), `$1${written[id]}`);
    writeFileSync(p, src);
  }

  return {
    errors,
    stats: {
      modules: modules.length,
      lessons: lessons.length,
      atoms: lessons.reduce((n, l) => n + l.atoms.length, 0),
      netlabs: labs, calcs, terminals: terms, captures: caps, snippets, challenges,
    },
  };
}
