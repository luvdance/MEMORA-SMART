/**
 * Prisma migrations for the Backend Engineering labs, made by the REAL
 * Prisma CLI (7.10.1, pinned in scripts/node-lab).
 *
 * The labs' first two migrations are the ones recorded in the w11-prisma
 * terminal session. Later steps (for example seats and payments) are made
 * here with `prisma migrate diff --from-schema <before> --to-schema <after>
 * --script`: the same SQL `prisma migrate dev` writes for that change.
 * Every schema used by a lab is also checked with `prisma format`, so the
 * schema a learner reads is laid out as Prisma lays it out.
 *
 *   node scripts/bePrisma.mjs          write src/academy/data/lessons/be-prisma.js
 *   node scripts/bePrisma.mjs --check  fail if that file is out of date (scripts/beCheck.mjs runs this)
 */
import { spawnSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, symlinkSync, writeFileSync, existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
const OUT = join(ROOT, "src/academy/data/lessons/be-prisma.js");
const WORKSPACE = join(ROOT, "scripts", "node-lab");
const P = await import(pathToFileURL(join(ROOT, "src/academy/data/lessons/be-projects.js")).href);

/** Schema changes the labs need, in order: name → [before, after]. */
export const STEPS = {
  seats_payments: ["W11_SCHEMA_LEVEL", "W11_SCHEMA_SEATS"],
};
/** Schemas the labs show, which must be as `prisma format` writes them. */
const SCHEMAS = ["W11_SCHEMA", "W11_SCHEMA_LEVEL", "W11_SCHEMA_SEATS", "W11_SCHEMA_MAPPED"];

const dir = mkdtempSync(join(tmpdir(), "be-prisma-"));
symlinkSync(join(WORKSPACE, "node_modules"), join(dir, "node_modules"), "junction");
// The schema engine will not start without a datasource (and the CLI then prints nothing and exits 0).
// A schema-to-schema diff never connects, so this URL is only a placeholder.
writeFileSync(join(dir, "package.json"), '{ "type": "module" }\n');
writeFileSync(
  join(dir, "prisma.config.ts"),
  'import { defineConfig } from "prisma/config";\n\nexport default defineConfig({ datasource: { url: "postgresql://diff:diff@localhost:5432/diff" } });\n'
);
const prisma = (args) => {
  const r = spawnSync(process.execPath, [join(WORKSPACE, "node_modules", "prisma", "build", "index.js"), ...args], {
    cwd: dir,
    encoding: "utf8",
    env: { ...process.env, PRISMA_HIDE_UPDATE_MESSAGE: "1", CHECKPOINT_DISABLE: "1", NO_COLOR: "1" },
  });
  if (r.status !== 0) throw new Error(`prisma ${args.join(" ")} failed:\n${r.stdout}\n${r.stderr}`);
  return r.stdout.replace(/\r\n/g, "\n");
};

try {
  const problems = [];
  for (const name of SCHEMAS) {
    writeFileSync(join(dir, "schema.prisma"), P[name]);
    prisma(["format", "--schema", "schema.prisma"]);
    const formatted = readFileSync(join(dir, "schema.prisma"), "utf8");
    if (formatted !== P[name]) problems.push(`${name} is not laid out as prisma format writes it. Formatted:\n${formatted}`);
  }
  const migrations = {};
  for (const [step, [before, after]] of Object.entries(STEPS)) {
    writeFileSync(join(dir, "before.prisma"), P[before]);
    writeFileSync(join(dir, "after.prisma"), P[after]);
    const out = prisma(["migrate", "diff", "--from-schema", "before.prisma", "--to-schema", "after.prisma", "--script"]);
    migrations[step] = out.replace(/^Loaded Prisma config[^\n]*\n\n?/, "");
  }
  const text = `/**
 * GENERATED by scripts/bePrisma.mjs with the real Prisma CLI 7.10.1: the SQL
 * \`prisma migrate dev\` writes for each schema change below (from
 * \`prisma migrate diff --from-schema … --to-schema … --script\`). Do not edit.
 */

export const PRISMA_MIGRATIONS = ${JSON.stringify(migrations, null, 2)};
`;
  if (process.argv.includes("--check")) {
    const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
    if (current !== text) problems.push("src/academy/data/lessons/be-prisma.js is out of date: run node scripts/bePrisma.mjs");
  } else {
    writeFileSync(OUT, text);
    console.log(`wrote ${OUT.replace(ROOT, "")}`);
  }
  if (problems.length) {
    console.error(problems.join("\n\n"));
    process.exitCode = 1;
  } else console.log("prisma: schemas formatted, migrations up to date");
} finally {
  rmSync(dir, { recursive: true, force: true });
}
