/**
 * Regenerates the two Codebase Engineering registries from the course
 * outline: src/academy/data/lessons/ce-registry.js (client) and
 * lib/academy/assessments/ce-registry.js (server). A module is registered as
 * soon as its lesson file exists, in outline order, so a half-written course
 * never imports a file that is not there.
 *
 * It also keeps each module's `atoms:` in the outline equal to the atoms
 * actually written (the tests require it). A module not yet written keeps an
 * estimate of two atoms per curriculum topic, so the XP calibration test
 * projects the unfinished course instead of measuring a fragment.
 *
 * Run:  node scripts/ceRegistries.mjs
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import {
  CODEBASE_ENGINEERING_COURSE,
  CODEBASE_ENGINEERING_MODULE_IDS,
} from "../src/academy/data/codebaseEngineeringCourse.js";

const ROOT = new URL("../", import.meta.url);
const written = CODEBASE_ENGINEERING_MODULE_IDS.filter((id) =>
  existsSync(new URL(`src/academy/data/lessons/${id}.js`, ROOT))
);
const alias = (id) => id.replace(/^ce-/, "CE_").replace(/-.*$/, "").toUpperCase();

const lessons = `/**
 * CODEBASE ENGINEERING — LESSON REGISTRY
 *
 * GENERATED by scripts/ceRegistries.mjs from the course outline. One import
 * per written module; a module with no entry shows as "being written".
 */

${written.map((id) => `import { LESSONS as ${alias(id)} } from "./${id}.js";`).join("\n")}

export const CODEBASE_ENGINEERING_LESSONS = {
${written.map((id) => `  "${id}": ${alias(id)},`).join("\n")}
};

export default CODEBASE_ENGINEERING_LESSONS;
`;

const assessments = `/**
 * ASSESSMENTS · CODEBASE ENGINEERING — REGISTRY
 *
 * ═════════════════════════════════════════════════════════════════════════
 * SERVER ONLY. Never import this from anything under src/.
 * ═════════════════════════════════════════════════════════════════════════
 *
 * GENERATED by scripts/ceRegistries.mjs. One bank per module, merged into a
 * single lessonId → assessment map for the grader in lib/academy/grade.js.
 */

${written.map((id) => `import { ASSESSMENTS as ${alias(id)} } from "./${id}.js";`).join("\n")}

export const CODEBASE_ENGINEERING_ASSESSMENTS = {
${written.map((id) => `  ...${alias(id)},`).join("\n")}
};

export default CODEBASE_ENGINEERING_ASSESSMENTS;
`;

writeFileSync(new URL("src/academy/data/lessons/ce-registry.js", ROOT), lessons);
writeFileSync(new URL("lib/academy/assessments/ce-registry.js", ROOT), assessments);

const outlineUrl = new URL("src/academy/data/codebaseEngineeringCourse.js", ROOT);
let outline = readFileSync(outlineUrl, "utf8");
for (const module of CODEBASE_ENGINEERING_COURSE.months.flatMap((m) => m.modules)) {
  let count = module.curriculum.length * 2;
  if (written.includes(module.id)) {
    const { LESSONS } = await import(new URL(`src/academy/data/lessons/${module.id}.js`, ROOT).href);
    count = LESSONS.reduce((n, l) => n + l.atoms.length, 0);
  }
  const re = new RegExp(`(id: "${module.id}",[\\s\\S]*?atoms: )\\d+`);
  outline = outline.replace(re, (m, head) => `${head}${count}`);
}
writeFileSync(outlineUrl, outline);

console.log(`registered ${written.length} of ${CODEBASE_ENGINEERING_MODULE_IDS.length} modules`);
