/**
 * Builds the React lab runtime: src/academy/react/labRuntimeEntry.js bundled
 * with esbuild into public/lab/react-runtime.js (React in development mode,
 * so learners see React's real warnings), plus Tailwind's browser build for
 * the styling module. Writes src/academy/react/runtimeVersion.js with a hash
 * of both, so a rebuilt runtime is never served from a stale cache.
 *
 * Run:  node scripts/reactLabRuntime.mjs   (after changing the entry or a library)
 */
import { createHash } from "node:crypto";
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { build } from "esbuild";

const ROOT = new URL("../", import.meta.url);
const out = new URL("public/lab/", ROOT);
mkdirSync(out, { recursive: true });

await build({
  entryPoints: [new URL("src/academy/react/labRuntimeEntry.js", ROOT).pathname.replace(/^\/([A-Z]:)/, "$1")],
  outfile: new URL("react-runtime.js", out).pathname.replace(/^\/([A-Z]:)/, "$1"),
  bundle: true,
  format: "iife",
  platform: "browser",
  target: "es2020",
  minify: true,
  legalComments: "none",
  define: { "process.env.NODE_ENV": '"development"', global: "globalThis" },
  logLevel: "warning",
});

copyFileSync(
  new URL("node_modules/@tailwindcss/browser/dist/index.global.js", ROOT),
  new URL("tailwind-browser.js", out)
);

const hash = createHash("sha256")
  .update(readFileSync(new URL("react-runtime.js", out)))
  .update(readFileSync(new URL("tailwind-browser.js", out)))
  .digest("hex")
  .slice(0, 12);

writeFileSync(
  new URL("src/academy/react/runtimeVersion.js", ROOT),
  `/** GENERATED by scripts/reactLabRuntime.mjs. A hash of the lab runtime files. */\nexport const REACT_RUNTIME_VERSION = "${hash}";\n`
);

const size = (name) => `${(readFileSync(new URL(name, out)).length / 1024).toFixed(0)} KB`;
console.log(`react-runtime.js ${size("react-runtime.js")}, tailwind-browser.js ${size("tailwind-browser.js")}, version ${hash}`);
