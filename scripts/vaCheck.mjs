/**
 * VIRTUAL ASSISTANT — REGISTRIES AND FAST CHECK
 *
 * 1. Regenerates the two registries from the course outline:
 *    src/academy/data/lessons/va-registry.js (client) and
 *    lib/academy/assessments/va-registry.js (server). A module is registered
 *    as soon as its lesson file exists, in outline order.
 * 2. Keeps each module's `atoms:` in the outline equal to the atoms written.
 *    A module not yet written keeps an estimate (curriculum topics + 1).
 * 3. Checks the written modules the way validate:content and test:academy
 *    will: coverage of the curriculum table, unique ids, one graded practice
 *    per atom, a lab (deskLab, writingLab or exercise) in every lesson,
 *    decisions with real answers, 4–5 questions per lesson pointing at real
 *    atoms with a whyWrong per option.
 * 4. Proves every lab: Workdesks (lib/academy/desk/check.mjs) and writing labs
 *    (model passes, starter fails), and every spreadsheet exercise's model
 *    formula (lib/academy/desk/sheetSolutions.mjs) gives its expected value.
 *
 * Run:  node scripts/vaCheck.mjs              all written modules
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { VIRTUAL_ASSISTANT_COURSE, VIRTUAL_ASSISTANT_MODULE_IDS } from "../src/academy/data/virtualAssistantCourse.js";
import { verifyWritingLabs } from "../lib/academy/writing/check.mjs";
import { verifyDeskLabs } from "../lib/academy/desk/check.mjs";
import { VA_EXERCISE_SOLUTIONS } from "../lib/academy/desk/sheetSolutions.mjs";
import { evaluateFormula } from "../lib/academy/spreadsheet/engine.js";

const ROOT = new URL("../", import.meta.url);

const written = VIRTUAL_ASSISTANT_MODULE_IDS.filter((id) =>
  existsSync(new URL(`src/academy/data/lessons/${id}.js`, ROOT)) &&
  existsSync(new URL(`lib/academy/assessments/${id}.js`, ROOT))
);
const alias = (id) => id.replace(/^va-/, "VA_").replace(/-.*$/, "").toUpperCase();

writeFileSync(new URL("src/academy/data/lessons/va-registry.js", ROOT), `/**
 * VIRTUAL ASSISTANT — LESSON REGISTRY
 *
 * GENERATED by scripts/vaCheck.mjs from the course outline. One import per
 * written module; a module with no entry shows as "coming soon".
 */

${written.map((id) => `import { LESSONS as ${alias(id)} } from "./${id}.js";`).join("\n")}

export const VIRTUAL_ASSISTANT_LESSONS = {
${written.map((id) => `  "${id}": ${alias(id)},`).join("\n")}
};

export default VIRTUAL_ASSISTANT_LESSONS;
`);

writeFileSync(new URL("lib/academy/assessments/va-registry.js", ROOT), `/**
 * ASSESSMENTS · VIRTUAL ASSISTANT — REGISTRY
 *
 * ═════════════════════════════════════════════════════════════════════════
 * SERVER ONLY. Never import this from anything under src/.
 * ═════════════════════════════════════════════════════════════════════════
 *
 * GENERATED by scripts/vaCheck.mjs. One bank per module, merged into a
 * single lessonId → assessment map for the grader in lib/academy/grade.js.
 */

${written.map((id) => `import { ASSESSMENTS as ${alias(id)} } from "./${id}.js";`).join("\n")}

export const VIRTUAL_ASSISTANT_ASSESSMENTS = {
${written.map((id) => `  ...${alias(id)},`).join("\n")}
};

export default VIRTUAL_ASSISTANT_ASSESSMENTS;
`);

const outlineUrl = new URL("src/academy/data/virtualAssistantCourse.js", ROOT);
let outline = readFileSync(outlineUrl, "utf8");
const modules = VIRTUAL_ASSISTANT_COURSE.months.flatMap((m) => m.modules);
const loaded = {};
for (const module of modules) {
  let count = module.curriculum.length + 1;
  if (written.includes(module.id)) {
    const { LESSONS } = await import(new URL(`src/academy/data/lessons/${module.id}.js`, ROOT).href);
    const { ASSESSMENTS } = await import(new URL(`lib/academy/assessments/${module.id}.js`, ROOT).href);
    loaded[module.id] = { LESSONS, ASSESSMENTS };
    count = LESSONS.reduce((n, l) => n + l.atoms.length, 0);
  }
  const re = new RegExp(`(id: "${module.id}",[\\s\\S]*?atoms: )\\d+`);
  outline = outline.replace(re, (m, head) => `${head}${count}`);
}
writeFileSync(outlineUrl, outline);

/* ── Structure ─────────────────────────────────────────────────────────── */
const errors = [];
const GRADED = ["deskLab", "writingLab", "exercise", "decision"];
const atomIds = new Set();
const lessonIds = new Set();
const qIds = new Set();
let lessons = 0;
let atoms = 0;
let questions = 0;
let sheets = 0;
const written_lessons = [];

for (const module of modules.filter((m) => written.includes(m.id))) {
  const { LESSONS, ASSESSMENTS } = loaded[module.id];
  const required = module.curriculum.map(([n]) => n);
  const covered = LESSONS.flatMap((l) => l.covers || []);
  const missing = required.filter((n) => !covered.includes(n));
  const extra = covered.filter((n) => !required.includes(n));
  if (missing.length) errors.push(`${module.id}: topics not taught: ${missing.join(", ")}`);
  if (extra.length) errors.push(`${module.id}: topics from elsewhere: ${extra.join(", ")}`);
  if (covered.join() !== required.filter((n) => covered.includes(n)).join()) {
    errors.push(`${module.id}: lessons do not follow the curriculum order`);
  }
  if (!LESSONS[LESSONS.length - 1]?.task?.prompts?.length) errors.push(`${module.id}: last lesson has no module task`);
  if (!LESSONS[LESSONS.length - 1]?.covers?.includes(`${module.order}.P`)) {
    errors.push(`${module.id}: the practical (${module.order}.P) is not in the last lesson`);
  }

  for (const lesson of LESSONS) {
    lessons += 1;
    if (lessonIds.has(lesson.id)) errors.push(`duplicate lesson id ${lesson.id}`);
    lessonIds.add(lesson.id);
    if (lesson.moduleId !== module.id) errors.push(`${lesson.id}: moduleId ${lesson.moduleId}`);
    written_lessons.push(lesson);
    if (!lesson.atoms.some((a) => a.deskLab || a.writingLab || a.exercise)) errors.push(`${lesson.id}: no lab (deskLab, writingLab or exercise)`);
    for (const atom of lesson.atoms) {
      atoms += 1;
      if (atomIds.has(atom.id)) errors.push(`duplicate atom id ${atom.id}`);
      atomIds.add(atom.id);
      if (!atom.id.startsWith("a-va-")) errors.push(`${atom.id}: atom ids start with a-va-`);
      if (!atom.explain) errors.push(`${atom.id}: no explanation`);
      if (atom.code || atom.webLab) errors.push(`${atom.id}: VA lessons do not use code or webLab`);
      if (atom.exercise) {
        sheets += 1;
        const f = VA_EXERCISE_SOLUTIONS[atom.id];
        if (!f) errors.push(`${atom.id}: no model formula in lib/academy/desk/sheetSolutions.mjs`);
        else {
          const r = evaluateFormula(f, atom.exercise.data || {});
          const ok = typeof atom.exercise.expected === "number" ? r.ok && Math.abs(Number(r.value) - atom.exercise.expected) < 0.005 : r.ok && String(r.value) === String(atom.exercise.expected);
          if (!ok) errors.push(`${atom.id}: model ${f} gives ${r.ok ? r.value : r.error}, expected ${atom.exercise.expected}`);
        }
        if (atom.exercise.lockedCells?.includes(atom.exercise.target)) errors.push(`${atom.id}: target cell is locked`);
      }
      const graded = GRADED.filter((k) => atom[k]);
      if (graded.length > 1) errors.push(`${atom.id}: ${graded.length} graded practices`);
      if (atom.decision) {
        const d = atom.decision;
        if (!d.options?.some((o) => o.id === d.correct)) errors.push(`${atom.id}: decision answer is not an option`);
        for (const o of d.options || []) {
          if (o.id === d.correct && !o.why) errors.push(`${atom.id}: correct option has no why`);
          if (o.id !== d.correct && !o.whyWrong) errors.push(`${atom.id}: option ${o.id} has no whyWrong`);
        }
      }
    }
    const a = ASSESSMENTS[lesson.id];
    if (!a) { errors.push(`${lesson.id}: no assessment`); continue; }
    if (a.questions.length < 4 || a.questions.length > 5) errors.push(`${lesson.id}: ${a.questions.length} questions`);
    for (const q of a.questions) {
      questions += 1;
      if (qIds.has(q.id)) errors.push(`duplicate question id ${q.id}`);
      qIds.add(q.id);
      if (!lesson.atoms.some((x) => x.id === q.atomId)) errors.push(`${q.id}: atom ${q.atomId} is not in ${lesson.id}`);
      if (!q.options.some((o) => o.id === q.correct)) errors.push(`${q.id}: key is not an option`);
      if (!q.explanation) errors.push(`${q.id}: no explanation`);
      for (const o of q.options) if (o.id !== q.correct && !q.whyWrong?.[o.id]) errors.push(`${q.id}: ${o.id} has no whyWrong`);
    }
  }
  for (const id of Object.keys(ASSESSMENTS)) if (!LESSONS.some((l) => l.id === id)) errors.push(`assessment ${id} has no lesson`);
}

// Atom ids must be unique across the WHOLE academy (validate:content checks it).
const { getCourseLessons } = await import(new URL("src/academy/data/lessons/index.js", ROOT).href).catch(() => ({}));
if (getCourseLessons) {
  const { CATALOG } = await import(new URL("src/academy/data/catalog.js", ROOT).href);
  const others = new Set();
  for (const entry of CATALOG.filter((c) => c.course && c.slug !== "virtual-assistant")) {
    for (const l of getCourseLessons(entry.slug)) for (const a of l.atoms) others.add(a.id);
  }
  for (const id of atomIds) if (others.has(id)) errors.push(`atom id ${id} is used by another course`);
}

const proof = verifyWritingLabs(written_lessons);
errors.push(...proof.errors);
const desk = verifyDeskLabs(written_lessons);
errors.push(...desk.errors);
const xp = lessons * 115 + atoms * 10;
console.log(`${written.length}/${modules.length} modules · ${lessons} lessons · ${atoms} atoms · ${questions} questions · ${desk.stats.labs} desks (${desk.stats.items} items) · ${proof.stats.labs} writing labs · ${sheets} sheets · ~${xp} XP`);

if (errors.length) {
  console.log(`
${errors.length} problem(s):`);
  for (const e of errors) console.log("  ✗ " + e);
  process.exit(1);
}
console.log("all good");
