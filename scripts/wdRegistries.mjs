/**
 * Regenerates the two Responsive Web Development registries from the course
 * outline: src/academy/data/lessons/wd-registry.js (client) and
 * lib/academy/assessments/wd-registry.js (server). A module is registered as
 * soon as its lesson file exists, in outline order, so a half-written course
 * never imports a file that is not there.
 *
 * It also keeps each module's `atoms:` in the outline equal to the atoms
 * actually written (the tests require it). A module not yet written keeps an
 * estimate of one atom per curriculum topic plus one, so the XP calibration
 * test projects the unfinished course instead of measuring a fragment.
 *
 * Run:  node scripts/wdRegistries.mjs
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { WEB_DEVELOPMENT_COURSE, WEB_DEVELOPMENT_MODULE_IDS } from "../src/academy/data/webDevelopmentCourse.js";

const ROOT = new URL("../", import.meta.url);
const written = WEB_DEVELOPMENT_MODULE_IDS.filter((id) =>
  existsSync(new URL(`src/academy/data/lessons/${id}.js`, ROOT))
);
const alias = (id) => id.replace(/^wd-/, "WD_").replace(/-.*$/, "").toUpperCase();

const lessons = `/**
 * RESPONSIVE WEB DEVELOPMENT — LESSON REGISTRY
 *
 * GENERATED by scripts/wdRegistries.mjs from the course outline. One import
 * per written module; a module with no entry shows as "coming soon".
 */

${written.map((id) => `import { LESSONS as ${alias(id)} } from "./${id}.js";`).join("\n")}

export const WEB_DEVELOPMENT_LESSONS = {
${written.map((id) => `  "${id}": ${alias(id)},`).join("\n")}
};

export default WEB_DEVELOPMENT_LESSONS;
`;

const assessments = `/**
 * ASSESSMENTS · RESPONSIVE WEB DEVELOPMENT — REGISTRY
 *
 * ═════════════════════════════════════════════════════════════════════════
 * SERVER ONLY. Never import this from anything under src/.
 * ═════════════════════════════════════════════════════════════════════════
 *
 * GENERATED by scripts/wdRegistries.mjs. One bank per module, merged into a
 * single lessonId → assessment map for the grader in lib/academy/grade.js.
 */

${written.map((id) => `import { ASSESSMENTS as ${alias(id)} } from "./${id}.js";`).join("\n")}

export const WEB_DEVELOPMENT_ASSESSMENTS = {
${written.map((id) => `  ...${alias(id)},`).join("\n")}
};

export default WEB_DEVELOPMENT_ASSESSMENTS;
`;

writeFileSync(new URL("src/academy/data/lessons/wd-registry.js", ROOT), lessons);
writeFileSync(new URL("lib/academy/assessments/wd-registry.js", ROOT), assessments);
const outlineUrl = new URL("src/academy/data/webDevelopmentCourse.js", ROOT);
let outline = readFileSync(outlineUrl, "utf8");
for (const module of WEB_DEVELOPMENT_COURSE.months.flatMap((m) => m.modules)) {
  let count = module.curriculum.length + 1;
  if (written.includes(module.id)) {
    const { LESSONS } = await import(new URL(`src/academy/data/lessons/${module.id}.js`, ROOT).href);
    count = LESSONS.reduce((n, l) => n + l.atoms.length, 0);
  }
  const re = new RegExp(`(id: "${module.id}",[\\s\\S]*?atoms: )\\d+`);
  outline = outline.replace(re, (m, head) => `${head}${count}`);
}
writeFileSync(outlineUrl, outline);

console.log(`registered ${written.length} of ${WEB_DEVELOPMENT_MODULE_IDS.length} modules`);
