import { useParams } from "react-router-dom";
import useSEO from "../../hooks/useSEO";
import Shell from "../Shell";
import { useLoad } from "../api";
import { Notice, Spinner, Stamp } from "../Bits";
import { longDate } from "../format";
import { STAGES, TIERS } from "../data/skills";
import { ShieldCheck } from "../icons";

/** What a stranger sees: proof only, nothing claimed, no contact details. */
export default function PublicPassport() {
  const { id } = useParams();
  const { data, error, loading } = useLoad("passport-public", { id });
  useSEO({ title: `${data?.name || "Skill Passport"} — Memotify`, description: "Skills proved on Memotify." });

  if (loading && !data) return <Shell tabs={false}><Spinner /></Shell>;
  if (error) {
    return <Shell tabs={false}><Notice title="This Passport is private or does not exist" /></Shell>;
  }

  return (
    <Shell tabs={false}>
      <div className="mf-book">
        <header className="mf-book__cover">
          <p className="mf-eyebrow">Skill Passport</p>
          <h1>{data.name}</h1>
          <p>{STAGES.find((s) => s.id === data.stage)?.label}</p>
        </header>

        {data.proof.length === 0 ? (
          <Notice title="No proven skills yet" />
        ) : (
          <div className="mf-stamps">
            {data.proof.map((entry) => (
              <Stamp
                key={entry.skill}
                tier={entry.tier}
                skill={entry.skill}
                line={`${entry.score != null ? `${entry.score}% · ` : ""}${entry.at ? longDate(entry.at) : entry.ref || entry.source}`}
              />
            ))}
          </div>
        )}

        <section className="mf-panel">
          <h2><ShieldCheck size={20} weight="fill" /> What these stamps mean</h2>
          <p className="mf-panel__sub"><b>{TIERS.certified.label}:</b> {TIERS.certified.note} of Memora Smart Academy, graded by our server.</p>
          <p className="mf-panel__sub"><b>{TIERS.verified.label}:</b> {TIERS.verified.note}. Valid for 18 months.</p>
          <p className="mf-panel__sub">This page is generated by Memotify and can't be edited by its owner.</p>
        </section>
      </div>
    </Shell>
  );
}
