/**
 * RESPONSIVE WEB DEVELOPMENT
 *
 * Authored from the Memora Smart Technologies curriculum: six phases, from
 * "what is a website?" to a deployed, accessible, responsive application and
 * a portfolio that presents it. React is deliberately NOT here: it is a course
 * of its own (WD-201), taken after this one. Everything in this course is the
 * platform itself (HTML, CSS, JavaScript and the browser), which is what every
 * framework is built on and what interviews test.
 *
 * Course content is DATA, never markup, in exactly the shape of the other
 * courses, so the catalog, sidebar, player, progress engine and stats band
 * render it without a change.
 *
 *   courses/{courseId}
 *     └── modules/{moduleId}          one curriculum module, or a phase's projects
 *           └── lessons/{lessonId}    three or four curriculum topics
 *                 └── atoms/{atomId}  one idea each
 *
 * ── THE PRACTICE IS BUILDING PAGES ───────────────────────────────────────
 * From Module 3 onwards every lesson contains a `webLab`: real files
 * (index.html, style.css, app.js) the learner edits while a live preview
 * renders them at phone, tablet and laptop widths. "Check my page" runs the
 * lab's checks against the rendered page (the DOM, computed styles, the
 * width of the viewport), and `npm run validate:content` loads every lab in
 * headless Chrome: its model answer must pass and its starter must fail.
 * JavaScript "what does this print?" exercises are run in Node.
 *
 * ── PHASES AND GATES ─────────────────────────────────────────────────────
 * Each phase ends with a projects module: one lesson per project in the
 * source curriculum and one for the phase's assessment gate, whose lab is
 * built without a model answer to copy (`revealSolution: false`).
 *
 * ── THE CURRICULUM TABLE ─────────────────────────────────────────────────
 * `curriculum` on each module is the source document's topic list, numbered
 * as it is there. Modules 28 to 30 of the source (React) are taught in WD-201,
 * so the source's Modules 31 to 35 are Modules 28 to 32 here. Every lesson
 * declares the numbers it `covers`, and `npm run test:academy` fails if any
 * topic is not taught.
 */

